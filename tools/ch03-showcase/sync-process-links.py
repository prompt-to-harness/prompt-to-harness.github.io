#!/usr/bin/env python3
"""Keep old excerpt URLs as routes to originals; leave artifact-only sections intact."""
import json
import os
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
config=json.loads(Path(__file__).with_name('inspect-process.json').read_text())
target=ROOT/'courseware/ch03/materials/inspect-process-routes.js'
routes={path:'http://127.0.0.1:4397/inspect/?topic='+topic for path,topic in config['routes'].items()}
target.write_text('/* Generated by tools/ch03-showcase/sync-process-links.py. */\n(()=>{\nconst routes='+json.dumps(routes,ensure_ascii=False,indent=2)+''';
function route(){const key=Object.keys(routes).find(key=>(location.pathname+location.hash).endsWith('/'+key));if(key)location.replace(routes[key]);}
addEventListener('hashchange',route);route();
})();
''')
for path in {key.split('#')[0] for key in routes}:
 p=ROOT/path
 if not p.exists():raise FileNotFoundError(p)
 source=os.path.relpath(target,p.parent)
 tag=f'<script src="{source}"></script>'
 text=p.read_text()
 if tag not in text:
  if '</body>' in text: text=text.replace('</body>',tag+'</body>')
  elif '</html>' in text: text=text.replace('</html>',tag+'</html>')
  else: text += '\n'+tag+'\n'
  p.write_text(text)
print(f'Process routes: {len(routes)} legacy anchors')
